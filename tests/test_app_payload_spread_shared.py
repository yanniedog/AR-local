def test_shared_spread_preserves_original_eight_day_real_payload_bytes():
    observations = json.loads(FIXTURE.read_bytes())["observations"]
    days = [item["date"] for item in observations]
    history = spread.BankSpreadHistory(days, run_date=days[-1])
    for item in observations:
        rows = deepcopy(item["queries"]["bank_rates"]["rows"])
        before = deepcopy(rows)
        history.observe(item["date"], rows)
        assert rows == before
        rows.clear()  # Only reduced cohort values may survive the next day.
    raw = json.dumps(history.finish(), ensure_ascii=False, sort_keys=True,
                     separators=(",", ":")).encode()
    # Independently generated by the unchanged 6c26 standalone builder.
    assert hashlib.sha256(raw).hexdigest() == "de613af6e97e50ebc8b45d31abc4ddd92d67caaccf890c09de437b38b580dd8b"


@pytest.mark.parametrize("days", [[DAY, DAY], [DAY, "2026-09-12"]])
def test_spread_rejects_invalid_declared_axes(days):
    with pytest.raises(ValueError, match="unique and ordered"):
        spread.BankSpreadHistory(days, run_date=DAY)


def test_spread_rejects_wrong_duplicate_and_incomplete_observations():
    history = spread.BankSpreadHistory(["2026-09-12", DAY], run_date=DAY)
    with pytest.raises(ValueError, match="declared dates"):
        history.observe(DAY, [])
    history.observe("2026-09-12", [])
    with pytest.raises(ValueError, match="declared dates"):
        history.observe("2026-09-12", [])
    with pytest.raises(ValueError, match="incomplete"):
        history.finish()
    history.observe(DAY, [])
    assert history.finish()["banks"] == {}
    with pytest.raises(ValueError, match="declared dates"):
        history.observe(DAY, [])


def test_shared_spread_uses_selected_revision_not_legacy_original(tmp_path, banks):
    original = save_export(tmp_path, {**banks, "rates": []})
    selected = save_export(tmp_path, banks, "corrected")
    save_export(tmp_path, {**banks, "rates": []}, "zz-unselected")
    history = spread.BankSpreadHistory([DAY], run_date=DAY)
    core = current_core(banks)
    list(history.observations(bank_rate_history_rows(core, original)))
    result = history.finish()
    assert result["banks"]["Bankwest"]["savings_mean"] == [0.02825]
    source = core["bank_rate_history_catalogue"]["sources"][DAY]
    selected_bytes = (selected / "dashboard-cache" / DAY / "banks.json").read_bytes()
    assert source["banks_sha256"] == hashlib.sha256(selected_bytes).hexdigest()
    assert source["kind"] == "selected_contract"


def test_shared_spread_unresolved_source_is_gap_without_legacy_fallback(tmp_path, banks):
    original = save_export(tmp_path, banks)
    save_export(tmp_path, {**banks, "rates": banks["rates"][:-1]}, "competing")
    (tmp_path / "state/observation-pointers-v2/latest-observation.json").unlink()
    for path in (tmp_path / "state/observation-selections-v1" / DAY).glob("*.json"):
        path.unlink()
    history = spread.BankSpreadHistory([DAY], run_date=DAY)
    core = current_core(banks)
    list(history.observations(bank_rate_history_rows(core, original)))
    assert history.finish()["banks"] == {}
    assert core["bank_rate_history_catalogue"]["unavailable_dates"] == {
        DAY: "historical_selection_unresolved"}


def test_production_builder_shares_unfiltered_verified_rows_once(tmp_path, banks, monkeypatch):
    exports = save_export(tmp_path, banks)
    monkeypatch.setattr(builder.cdr_brand_logos, "fetch_register_logos", lambda **_: {})
    monkeypatch.setenv("AR_LOCAL_RBA_OFFICIAL_FETCH", "0")
    original = spread.BankSpreadHistory.observe
    observed = []

    def observe(self, day, rows):
        observed.append((day, deepcopy(rows)))
        return original(self, day, rows)

    def forbidden(*args, **kwargs):
        pytest.fail("Production spread must not start a second history scan")

    monkeypatch.setattr(spread.BankSpreadHistory, "observe", observe)
    monkeypatch.setattr(spread, "build_bank_spread_history", forbidden)
    result = builder._compute_payload(exports)
    assert observed == [(DAY, banks["rates"])]
    assert result["bank_spread_history"]["banks"]["Bankwest"]["savings_mean"] == [0.02825]


def test_production_spread_preserves_unresolved_prior_day_gap(tmp_path, banks, monkeypatch):
    exports = save_export(tmp_path, banks, finalize=False)
    prior = json.loads(FIXTURE.read_bytes())["observations"][-2]
    day = prior["date"]
    # Two real-data storage copies with no selection proof must remain unknown.
    for suffix in ("_exports", "_revisions/unbound/_exports"):
        folder = tmp_path / "runs" / day / suffix / "dashboard-cache" / day
        folder.mkdir(parents=True)
        (folder / "banks.json").write_text(json.dumps({
            "run_date": day, "rates": prior["queries"]["bank_rates"]["rows"]}), encoding="utf-8")
    monkeypatch.setattr(builder.cdr_brand_logos, "fetch_register_logos", lambda **_: {})
    monkeypatch.setenv("AR_LOCAL_RBA_OFFICIAL_FETCH", "0")
    result = builder._compute_payload(exports)
    history = result["bank_spread_history"]
    assert history["run_dates"] == [day, DAY]
    assert history["banks"]["Bankwest"]["savings_mean"] == [None, 0.02825]
    assert history["banks"]["Bankwest"]["quality"] == ["missing_both", "missing_mortgage"]
    assert result["core"]["bank_rate_history_catalogue"]["unavailable_dates"] == {
        day: "historical_selection_unresolved"}
